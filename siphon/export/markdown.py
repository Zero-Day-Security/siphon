from __future__ import annotations

from datetime import datetime, timezone
from typing import Any


def evidence_to_markdown(
    evidence_list: list[dict[str, Any]],
    flows: dict[str, dict[str, Any]],
    title: str = "Siphon Security Assessment Report",
) -> str:
    sections: list[str] = []
    now = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    sections.append(f"# {title}\n")
    sections.append(f"**Generated:** {now}  ")
    sections.append(f"**Findings:** {len(evidence_list)}\n")
    sections.append("---\n")

    for i, ev in enumerate(evidence_list, 1):
        flow = flows.get(ev.get("flow_id", "")) or {}
        sections.append(_render_finding(i, ev, flow))

    sections.append("---\n")
    sections.append("*Report generated by [Siphon](https://github.com/siphon-proxy/siphon)*\n")
    return "\n".join(sections)


def flows_to_markdown(
    flow_list: list[dict[str, Any]],
    title: str = "Siphon Traffic Export",
) -> str:
    sections: list[str] = []
    now = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    sections.append(f"# {title}\n")
    sections.append(f"**Generated:** {now}  ")
    sections.append(f"**Flows:** {len(flow_list)}\n")
    sections.append("---\n")

    sections.append("| # | Method | URL | Status | Duration |")
    sections.append("|---|--------|-----|--------|----------|")
    for i, f in enumerate(flow_list, 1):
        method = f.get("method", "?")
        url = f.get("url", "?")
        if len(url) > 80:
            url = url[:77] + "..."
        status = f.get("status_code") or "—"
        dur = f.get("duration_ms")
        dur_str = f"{dur:.0f}ms" if dur else "—"
        sections.append(f"| {i} | `{method}` | `{url}` | {status} | {dur_str} |")

    sections.append("\n---\n")
    sections.append("*Exported by [Siphon](https://github.com/siphon-proxy/siphon)*\n")
    return "\n".join(sections)


def _render_finding(index: int, ev: dict[str, Any], flow: dict[str, Any]) -> str:
    method = flow.get("method", ev.get("method", "?"))
    url = flow.get("url", ev.get("url", "?"))
    status = flow.get("status_code", ev.get("status_code", "—"))
    ts = ev.get("timestamp", 0)
    ts_str = datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC") if ts else "—"

    lines: list[str] = []
    lines.append(f"## Finding {index}: `{method} {url}`\n")
    lines.append(f"**Status:** {status}  ")
    lines.append(f"**Captured:** {ts_str}\n")

    if ev.get("notes"):
        lines.append(f"**Notes:** {ev['notes']}\n")

    req_headers = flow.get("request_headers") or {}
    if req_headers:
        lines.append("### Request Headers\n")
        lines.append("```")
        for k, v in req_headers.items():
            lines.append(f"{k}: {v}")
        lines.append("```\n")

    req_body = flow.get("request_body")
    if req_body:
        lines.append("### Request Body\n")
        lines.append("```")
        lines.append(_truncate(req_body, 2000))
        lines.append("```\n")

    resp_headers = flow.get("response_headers") or {}
    if resp_headers:
        lines.append("### Response Headers\n")
        lines.append("```")
        for k, v in resp_headers.items():
            lines.append(f"{k}: {v}")
        lines.append("```\n")

    resp_body = flow.get("response_body")
    if resp_body:
        lines.append("### Response Body\n")
        lines.append("```")
        lines.append(_truncate(resp_body, 2000))
        lines.append("```\n")

    lines.append("---\n")
    return "\n".join(lines)


def _truncate(text: str, max_len: int) -> str:
    if len(text) > max_len:
        return text[:max_len] + "\n... (truncated)"
    return text
